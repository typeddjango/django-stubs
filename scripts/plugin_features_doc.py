"""Generate the mypy plugin feature list from the docstrings of the hooks the plugin entrypoint wires in.

Hooks are grouped by transformer module.
A module or hook docstring's first line is the section or feature title,
the rest (after a blank line) is its description.
Exits non-zero when one breaks that convention, so the doc can't silently drift from the code.
"""

from __future__ import annotations

import ast
import inspect
import sys
from collections import defaultdict
from pathlib import Path
from types import FunctionType, MethodType, ModuleType

from mypy_django_plugin import main

ROOT = Path(__file__).parent.parent

Hook = FunctionType | MethodType


def resolve(node: ast.expr) -> object:
    if isinstance(node, ast.Name):
        return vars(main).get(node.id)
    if isinstance(node, ast.Attribute):
        return getattr(resolve(node.value), node.attr, None)
    return None


def split_docstring(obj: Hook | ModuleType) -> tuple[str, str]:
    title, _, description = (inspect.getdoc(obj) or "").partition("\n")
    if not title or (description and not description.startswith("\n")):
        name = getattr(obj, "__qualname__", obj.__name__)
        sys.exit(f"`{name}` in {inspect.getfile(obj)} needs a docstring with a one-line title, then a blank line")
    return title, description.strip("\n")


if __name__ == "__main__":
    sections: defaultdict[ModuleType, set[Hook]] = defaultdict(set)
    for node in ast.walk(ast.parse(inspect.getsource(main.plugin("")))):
        if isinstance(node, ast.expr) and isinstance(obj := resolve(node), Hook):
            if obj.__module__.startswith("mypy_django_plugin.transformers."):
                sections[sys.modules[obj.__module__]].add(obj)

    blocks = [
        "# mypy plugin features",
        f"<!-- Generated by `{Path(__file__).name}` from the plugin hook docstrings, do not edit. -->",
    ]
    for module, hooks in sorted(sections.items(), key=lambda section: split_docstring(section[0])):
        title, description = split_docstring(module)
        path = Path(inspect.getfile(module)).relative_to(ROOT).as_posix()
        blocks += [f"## {title}", description]
        for hook in sorted(hooks, key=lambda hook: inspect.getsourcelines(hook)[1]):
            title, description = split_docstring(hook)
            blocks += [f"### {title}", description, f"Source: [`{path}`](../{path}) · Hook: `{hook.__qualname__}`"]
    (ROOT / "docs" / "mypy-plugin-features.md").write_text("\n\n".join(filter(None, blocks)) + "\n")
