"""Generate the mypy plugin feature list from the docstrings of the transformer modules the plugin entrypoint wires in.

A module docstring's first line is the section title,
the rest (after a blank line) is its user-facing description.
Exits non-zero when one breaks that convention, so the doc can't silently drift from the code.
"""

from __future__ import annotations

import ast
import inspect
import sys
from pathlib import Path
from types import FunctionType, MethodType, ModuleType

from mypy_django_plugin import main

ROOT = Path(__file__).parent.parent


def resolve(node: ast.expr) -> object:
    if isinstance(node, ast.Name):
        return vars(main).get(node.id)
    if isinstance(node, ast.Attribute):
        return getattr(resolve(node.value), node.attr, None)
    return None


def split_docstring(module: ModuleType) -> tuple[str, str]:
    title, _, description = (inspect.getdoc(module) or "").partition("\n\n")
    if not title or "\n" in title or not description.strip():
        path = Path(inspect.getfile(module)).relative_to(ROOT)
        sys.exit(f"{path} needs a module docstring with a one-line title, a blank line, then a description")
    return title, description.strip("\n")


if __name__ == "__main__":
    modules = {
        sys.modules[obj.__module__]
        for node in ast.walk(ast.parse(inspect.getsource(main.plugin(""))))
        if isinstance(node, ast.expr)
        and isinstance(obj := resolve(node), FunctionType | MethodType)
        and obj.__module__.startswith("mypy_django_plugin.transformers.")
    }
    blocks = [
        "# mypy plugin features",
        f"<!-- Generated by `{Path(__file__).name}` from the plugin module docstrings, do not edit. -->",
    ]
    for title, description in sorted(map(split_docstring, modules)):
        blocks += [f"## {title}", description]
    (ROOT / "docs" / "mypy-plugin-features.md").write_text("\n\n".join(blocks) + "\n")
